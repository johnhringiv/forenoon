-- The parts of a built-in source each reader reads: for Lobsters, "front" for its front page
-- and any of its tags. A reader with no rows for a source reads its front page alone.
CREATE TABLE builtin_sections (
    user_id TEXT NOT NULL,
    builtin TEXT NOT NULL,   -- the pipeline's key, as in sources.builtin
    section TEXT NOT NULL,
    PRIMARY KEY (user_id, builtin, section)
);

